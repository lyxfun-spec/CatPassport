export type LanguagePreference = 'system' | 'zh-CN' | 'en';
export type UiLanguage = 'zh-CN' | 'en';

export function isLanguagePreference(value: unknown): value is LanguagePreference {
  return value === 'system' || value === 'zh-CN' || value === 'en';
}

export function resolveLanguage(preference: LanguagePreference, systemLocale: string, preferredLanguages: string[] = []): UiLanguage {
  if (preference !== 'system') return preference;
  const locale = systemLocale.trim() || preferredLanguages[0] || '';
  return /^zh(?:[-_]|$)/i.test(locale) ? 'zh-CN' : 'en';
}

let language: UiLanguage = 'zh-CN';
export function setTranslationLanguage(value: UiLanguage): void { language = value; }
export function getTranslationLanguage(): UiLanguage { return language; }

// Source text is the Chinese fallback; placeholders keep user content separate from UI text.
export function t(source: string, ...values: (string | number | undefined)[]): string {
  const template = language === 'en' ? english[source] ?? source : source;
  if (values.length === 0) return template;
  return template.replace(/\{(\d+)\}/g, (_, index: string) => String(values[Number(index)] ?? ''));
}

